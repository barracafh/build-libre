// The data the site shows, cleaned and typed, read from data/ (the Escaño Abierto snapshot).
//
// Server only: it reads the disk, so call it from Server Components at build time and pass the
// client what it needs (e.g. `resumenes()` for the filters). Field meanings: data/README.md.
//
// Cleaning applied here:
// - Parties are the groups of src/config/partidos.json, with its names. The Grupo Mixto, the
//   Government, the Mesa and unknown codes are left out (the Mixto is not a party).
// - Each party's position is recomputed from its count with the upstream rule (escano/votaciones.py,
//   `posicion_grupo`): the most voted option if it reaches 80 % of the votes cast, otherwise
//   divided, keeping the majority option. A party where nobody voted is "X", never "?".
// - Topics are limited to TEMAS; `defensa` is folded into `exteriores`.
// - Upstream "?" and "" become null; the list of dissenting deputies is not exposed.
// - `motivos` are written by a language model upstream: show them labelled as generated, next to
//   the official vote, and never filter by them. Each one links its Diario de Sesiones when known.
// - Candidacies and parties come in alphabetical order, never by result.
// - Topic pages group votes into initiatives (`datosTemas`): amendment votes apart, an initiative
//   under every topic of its votes. Never a summary of a party's votes across initiatives.

import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export type Voto = "S" | "N" | "A" | "X";
export type Posicion = Voto | "D"; // labels and marks: src/components/vote-mark.tsx

// The fixed list of topics the site offers. Slugs are upstream `tm` tags (escano/temas.py),
// assigned by keywords, no AI. Upstream `cultura` and `tecnologia` are left out.
