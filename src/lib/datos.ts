// Upstream shapes, only the fields used here.
type VotacionOrigen = {
  id: string;
  fecha: string;
  tipo: string;
  titulo: string;
  texto: string;
  exp: string;
  proponente: string;
  si: number;
  no: number;
  abst: number;
  novota: number;
  conteo: Record<string, Partial<Record<Voto, number>>>;
  porque?: Record<string, [string, string, string, string]>;
  json: string;
  v: string;
  cg?: Record<string, string>;
  tm?: string[];
};
type SesionOrigen = {
  id: string;
  fecha: string;
  organo: string;
  ds: string | null;
  puntos: { votos?: string[] }[];
};
// [name, group, constituency, party, alta, x, y, seat code, baja]
type FilaDiputado = [string, string, string, string, string, number, number, number | "", string];

const UMBRAL = 0.8;

export function posicionPartido(conteo: Partial<Record<Voto, number>>): PosicionPartido {
  const c = { S: conteo.S ?? 0, N: conteo.N ?? 0, A: conteo.A ?? 0, X: conteo.X ?? 0 };
  const emitidos = c.S + c.N + c.A;
  if (!emitidos) return { posicion: "X", mayoritario: null, conteo: c };
  const mayoritario = (["S", "N", "A"] as const).reduce((a, b) => (c[b] > c[a] ? b : a));
  const posicion = c[mayoritario] / emitidos >= UMBRAL ? mayoritario : "D";
  return { posicion, mayoritario, conteo: c };
}

const nulo = (s: string) => (s === "" || s === "?" ? null : s);

export function limpiarVotacion(
  v: VotacionOrigen,
  codigos: string[],
  diarios: Record<string, string | null>,
): Votacion {
  const partidos: Record<string, PosicionPartido> = {};
  const motivos: Record<string, Motivo> = {};
  for (const codigo of codigos) {
    if (v.conteo[codigo]) partidos[codigo] = posicionPartido(v.conteo[codigo]);
    const m = v.porque?.[codigo];
    if (m) motivos[codigo] = { texto: m[0], orador: m[1], fecha: m[3], diario: diarios[m[2]] ?? null };
  }
  return {
    id: v.id,
    fecha: v.fecha,
    tipo: v.tipo,
    titulo: v.titulo,
    texto: v.texto,
    exp: nulo(v.exp),
    proponente: nulo(v.proponente),
    totales: { si: v.si, no: v.no, abstencion: v.abst, noVota: v.novota },
    temas: temasDe(v.tm),
    partidos,
    motivos,
    fuente: v.json,
  };
}

export function decodificarVotos(v: Pick<VotacionOrigen, "v" | "cg">, filas: FilaDiputado[]) {
  const votos: VotoDiputado[] = [];
  [...v.v].forEach((voto, i) => {
    if (voto === "-") return;
    const [nombre, grupo, circunscripcion, formacion] = filas[i];
    votos.push({ nombre, grupo: v.cg?.[i] ?? grupo, formacion, circunscripcion, voto: voto as Voto });
  });
  return votos;
}

const leer = (...ruta: string[]) =>
  JSON.parse(readFileSync(join(process.cwd(), ...ruta), "utf8"));

// Only the monthly files (YYYY-MM.json): the folders also hold upstream's per-day votes and
// per-session files, which have another shape.
const mensuales = <T>(carpeta: string): T[] =>
  readdirSync(join(process.cwd(), "data", carpeta))
    .filter((f) => /^\d{4}-\d{2}\.json$/.test(f))
    .sort()
    .flatMap((f) => leer("data", carpeta, f) as T[]);

const porNombre = (a: { nombre: string }, b: { nombre: string }) =>
  a.nombre.localeCompare(b.nombre, "es");

let cache: ReturnType<typeof cargar> | undefined;

function cargar() {
  const mapa = leer("src", "config", "partidos.json") as Record<string, Omit<Partido, "codigo">>;
  const partidos = Object.entries(mapa)
    .map(([codigo, p]) => ({ codigo, ...p }))
    .sort(porNombre);
  const codigos = partidos.map((p) => p.codigo);

  const diarios: Record<string, string | null> = {};
  const sesionesDe = new Map<string, Sesion[]>();
  for (const s of mensuales<SesionOrigen>("sesiones")) {
    diarios[s.id] = s.ds;
    const sesion = { id: s.id, fecha: s.fecha, organo: s.organo, diario: s.ds };
    for (const id of new Set(s.puntos.flatMap((p) => p.votos ?? []))) {
      sesionesDe.set(id, [...(sesionesDe.get(id) ?? []), sesion]);
    }
  }

  const origen = mensuales<VotacionOrigen>("votaciones").sort((a, b) => a.fecha.localeCompare(b.fecha));
  const votaciones = origen.map((v) => limpiarVotacion(v, codigos, diarios));

  const territorios = leer("data", "elecciones", "territorios.json");
  const provincias: Provincia[] = Object.entries(territorios.provincias as Record<string, { n: string }>)
    .map(([codigo, p]) => ({ codigo, nombre: p.n }))
    .sort(porNombre);

  return {
    partidos,
    votaciones,
    origen: new Map(origen.map((v) => [v.id, v])),
    sesionesDe,
    porId: new Map(votaciones.map((v) => [v.id, v])),
    filas: leer("data", "indice.json").diputados as FilaDiputado[],
    provincias,
    resultados: leer("data", "elecciones", "resultados-2023.json").prov,
    escanos: leer("data", "elecciones", "escanos-2026.json").escanos as Record<string, number>,
    fuente: leer("data", "source.json") as { commit: string; fetched: string },
  };
}

const datos = () => (cache ??= cargar());

// Parties in alphabetical order of their current name.
export const partidos = (): Partido[] => datos().partidos;

// Every Pleno vote of the XV legislature, oldest first.
export const votaciones = (): Votacion[] => datos().votaciones;

export const votacion = (id: string): Votacion | undefined => datos().porId.get(id);

export const resumenes = (): ResumenVotacion[] =>
  datos().votaciones.map(({ id, fecha, tipo, titulo, exp, temas, partidos }) => ({
    id,
    fecha,
    tipo,
    titulo,
    exp,
    temas,
    partidos: Object.fromEntries(Object.entries(partidos).map(([c, p]) => [c, p.posicion])),
  }));

// How each deputy voted, in the order of the upstream index. Empty for the 2 votes without detail.
export function votosDiputados(id: string): VotoDiputado[] {
  const v = datos().origen.get(id);
  return v ? decodificarVotos(v, datos().filas) : [];
}

// Provinces in alphabetical order, keyed by their two-digit INE code.
export const provincias = (): Provincia[] => datos().provincias;

export function resultados2023(codigo: string): Resultados2023 | undefined {
  const r = datos().resultados[codigo];
  const provincia = datos().provincias.find((p) => p.codigo === codigo);
  if (!r || !provincia) return undefined;
  return {
    provincia,
    escanos: r.e,
    censo: r.censo,
    validos: r.validos,
    blancos: r.blancos,
    nulos: r.nulos,
    electoresPorEscano: Math.round(r.censo / r.e),
    candidaturas: (r.c as [string, string, number, number][])
      .map(([siglas, , votos, escanos]) => ({ siglas, votos, escanos }))
      .sort((a, b) => a.siglas.localeCompare(b.siglas, "es")),
    fuente: FUENTES.resultados2023,
  };
}

// Seats the province elects on 29 November 2026 (Real Decreto 806/2026).
export const escanos2026 = (codigo: string): number | undefined => datos().escanos[codigo];

// Votes on amendments are titled "… (enmienda 12)", "(resto de las enmiendas)", "(votación en bloque
// de las enmiendas)". Amendments to the whole text ("enmienda a la totalidad") are main votes.
export const esEnmienda = (titulo: string) =>
  /\((resto de (las )?|votación en bloque de las )?enmienda/i.test(titulo);

const sinSufijo = (titulo: string) => titulo.replace(/\s*\((punto|votación|voto|enmienda|resto).*\)\s*$/i, "");

// Groups every vote into initiatives and files each initiative under every topic of its votes.
// Initiatives without a topic are left out and only counted.
export function datosTemas(): DatosTemas {
  const grupos = new Map<string, Votacion[]>();
  for (const v of votaciones()) {
    const k = v.exp ?? `${v.fecha}|${v.texto}`;
    grupos.set(k, [...(grupos.get(k) ?? []), v]);
  }

  const todas: Iniciativa[] = [...grupos.values()].map((vs) => {
    const principales = vs.filter((v) => !esEnmienda(v.titulo));
    const primera = principales[0] ?? vs[0];
    const sesiones = new Map(vs.flatMap((v) => datos().sesionesDe.get(v.id) ?? []).map((s) => [s.id, s]));
    return {
      clave: vs[0].exp ?? vs[0].id,
      tipo: primera.tipo,
      titulo: sinSufijo(primera.titulo),
      texto: primera.texto,
      proponente: vs.find((v) => v.proponente)?.proponente ?? null,
      fecha: vs.at(-1)!.fecha,
      temas: temasDe(vs.flatMap((v) => v.temas)),
      votaciones: principales,
      enmiendas: vs
        .filter((v) => esEnmienda(v.titulo))
        .map(({ id, fecha, titulo, fuente }) => ({ id, fecha, titulo, fuente })),
      sesiones: [...sesiones.values()].sort((a, b) => a.fecha.localeCompare(b.fecha) || a.id.localeCompare(b.id)),
    };
  });
  const recientes = todas
    .filter((i) => i.temas.length)
    .sort((a, b) => b.fecha.localeCompare(a.fecha) || a.clave.localeCompare(b.clave));
  const sinTema = todas.filter((i) => !i.temas.length);

  const { commit, fetched } = datos().fuente;
  return {
    instantanea: { commit, fecha: fetched },
    partidos: partidos(),
    temas: Object.entries(TEMAS).map(([slug, nombre]) => {
      const de = recientes.filter((i) => i.temas.includes(slug));
      return {
        slug,
        nombre,
        recuento: {
          iniciativas: de.length,
          votaciones: de.reduce((n, i) => n + i.votaciones.length, 0),
          enmiendas: de.reduce((n, i) => n + i.enmiendas.length, 0),
        },
        iniciativas: de.map((i) => i.clave),
      };
    }),
    iniciativas: Object.fromEntries(recientes.map((i) => [i.clave, i])),
    sinTema: {
      iniciativas: sinTema.length,
      votaciones: sinTema.reduce((n, i) => n + i.votaciones.length + i.enmiendas.length, 0),
    },
  };
}

// Pinned upstream commit and the date it was fetched, to show next to the data.
export const instantanea = () => {
  const { commit, fetched } = datos().fuente;
  return { commit, fecha: fetched, ultimaVotacion: datos().votaciones.at(-1)?.fecha };
};

let cacheTemas: DatosTemas | undefined;

// What the topic pages read: the committed data/temas.json, so the build does not regroup every
// vote for each page. A test keeps it equal to datosTemas().
export const temas = (): DatosTemas => (cacheTemas ??= leer("data", "temas.json"));

// ---------- Escáner político (/escaner) ----------
// The 2023 manifestos of PP, PSOE, Sumar and Vox against the Pleno votes: literal quotes per topic,
// each linked (blind AI judgement on the official bulletin text) to the votes that fulfil or
// contradict it. Built by scripts/escaner.ts from docs/programas-2023/posiciones/ into
// data/escaner.json. A party's vote there is the majority of the deputies elected on its 2023 list.
export type VotoEscaner = "S" | "N" | "A" | "D" | "";
export type DatosEscaner = {
  total: number; conTema: number; desde: string; hasta: string; amplias: number; tipos: Record<string, number>;
  partidos: { id: string; nombre: string; art: string; full: string; color: string }[];
  grupos: Record<string, string>;
  temas: { id: string; nombre: string; votaciones: number; frases: number; programa: number; sentidos: Record<string, Record<string, number>> }[];
  posiciones: Record<string, string>; cortas: Record<string, string>;
  frases: { id: string; tema: string; partido: string; cita: string; pagina: number; postura: string; subtema: string;
    enlaces: { v: string; s: "apoya" | "contradice"; rel: string; motivo: string }[] }[];
  votaciones: Record<string, {
    fecha: string; tipo: string; titulo: string; url: string; aprobada: boolean; proponente: string;
    si: number; no: number; abst: number; novota: number;
    conteo: Record<string, Record<string, number>>; votos: Record<string, VotoEscaner>; porque: Record<string, string>;
    noticias: { medio: string; titular: string; url: string; fecha: string }[];
  }>;
};

let cacheEscaner: DatosEscaner | undefined;
export const escaner = (): DatosEscaner => (cacheEscaner ??= leer("data", "escaner.json"));
